export function preferenceValue(value: CorePreferences, key: string): string | number | boolean {
  return key.split('.').reduce<unknown>((current, part) => (current as Record<string, unknown>)[part], value) as
    string | number | boolean;
}
/** Build only known paths, then let the canonical schema validate the complete value. */
export function preferencePatch(key: string, value: unknown): DeepPartial<CorePreferences> {
  if (!preferenceControls.some(control => control.key === key)) return {};
  if (key === 'theme.colorPrimary') {
    const validated = validateCorePreferencePatch({ theme: { colorPrimary: value } });
    if (!validated.theme?.colorPrimary) return {};
    return validateCorePreferencePatch({ theme: { preset: 'custom', colorPrimary: validated.theme.colorPrimary } });
  }
  const parts = key.split('.');
  let patch: unknown = value;
  for (const part of parts.reverse()) patch = { [part]: patch };
  return validateCorePreferencePatch(patch);
}
export function isValidPreferenceValue(key: string, value: unknown): boolean {
  const patch = preferencePatch(key, value);
  return Object.keys(patch).length > 0;
}
