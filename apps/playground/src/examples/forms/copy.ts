export type FormsText = (key: keyof typeof formsExampleEnglish) => string;
export function useFormsText(): FormsText {
  const { t } = useTranslation('app');
  return key => {
    const path = `examples.forms.${key}`;
    const translated = t(path);
    return translated === path || translated === `app:${path}` ? formsExampleEnglish[key] : translated;
  };
}
